param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('Store', 'Generate', 'Verify', 'ApplyRailway', 'UpdateEnv')]
    [string]$Action,
    [Parameter(Mandatory = $true)]
    [ValidateSet('qa', 'production')]
    [string]$Environment,
    [Parameter(Mandatory = $true)]
    [ValidateSet('SUPABASE_SERVICE_ROLE_KEY', 'DATABASE_URL', 'JWT_SECRET')]
    [string]$Variable,
    [Parameter(Mandatory = $true)]
    [string]$VaultRoot,
    [ValidateSet('api', 'web')]
    [string]$Service,
    [switch]$SkipDeploys,
    [switch]$PromptSecure
)

$ErrorActionPreference = 'Stop'
try {
    Add-Type -AssemblyName System.Security
    $repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..')).TrimEnd('\')
    $privateRoot = [IO.Path]::GetFullPath($VaultRoot).TrimEnd('\')
    if ($privateRoot.Equals($repoRoot, [StringComparison]::OrdinalIgnoreCase) -or $privateRoot.StartsWith($repoRoot + '\', [StringComparison]::OrdinalIgnoreCase)) {
        throw 'Private vault must be outside repository'
    }
    if (-not (Test-Path -LiteralPath $privateRoot -PathType Container)) { throw 'Create restricted private directory first' }
    $allowedSids = @([Security.Principal.WindowsIdentity]::GetCurrent().User.Value, 'S-1-5-18', 'S-1-5-32-544')
    foreach ($rule in [IO.Directory]::GetAccessControl($privateRoot).Access) {
        if ($rule.AccessControlType -eq 'Allow' -and $rule.IdentityReference.Translate([Security.Principal.SecurityIdentifier]).Value -notin $allowedSids) {
            throw 'Private directory has permissions for additional identities'
        }
    }
    $file = Join-Path $privateRoot "$Environment.$Variable.dpapi"
    $entropy = [Text.Encoding]::UTF8.GetBytes("APEXOS_RECOVERY_V1|$Environment|$Variable")
    if ($Action -in @('Store', 'Generate')) {
        # Use an anonymous stdin pipe. Never pass a secret as an argument or write it in plaintext.
        if ($Action -eq 'Generate') {
            if ($Variable -ne 'JWT_SECRET') { throw 'Provider credentials must be generated by the provider' }
            $random = New-Object byte[] 48
            $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
            try { $rng.GetBytes($random); $secret = [Convert]::ToBase64String($random) }
            finally { $rng.Dispose(); [Array]::Clear($random, 0, $random.Length) }
        } elseif ($PromptSecure) {
            $secureInput = Read-Host 'Paste new secret (hidden)' -AsSecureString
            $pointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secureInput)
            try { $secret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($pointer).Trim() }
            finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($pointer); $secureInput.Dispose() }
        } else { $secret = [Console]::In.ReadToEnd().Trim() }
        if (-not $secret -or $secret.Contains("`n") -or $secret.Contains("`r")) { throw 'Invalid secret input' }
        if ($Variable -eq 'SUPABASE_SERVICE_ROLE_KEY' -and -not $secret.StartsWith('sb_secret_')) { throw 'Expected newly issued secret key' }
        $plain = [Text.Encoding]::UTF8.GetBytes($secret)
        $cipher = [Security.Cryptography.ProtectedData]::Protect($plain, $entropy, [Security.Cryptography.DataProtectionScope]::CurrentUser)
        [IO.File]::WriteAllBytes($file, $cipher)
        [Array]::Clear($plain, 0, $plain.Length)
        $secret = $null
        Write-Output '{"stored":true,"encryption":"Windows DPAPI CurrentUser","plaintext_file":false}'
        exit 0
    }
    $plain = [Security.Cryptography.ProtectedData]::Unprotect([IO.File]::ReadAllBytes($file), $entropy, [Security.Cryptography.DataProtectionScope]::CurrentUser)
    $secret = [Text.Encoding]::UTF8.GetString($plain)
    [Array]::Clear($plain, 0, $plain.Length)
    if ($Action -eq 'Verify') {
        Write-Output '{"decryptable":true,"secret_disclosed":false}'
        exit 0
    }
    if ($Action -eq 'UpdateEnv') {
        $envFile = Join-Path $repoRoot $(if ($Environment -eq 'qa') { 'config/qa.env' } else { 'config/production.env' })
        $lines = [IO.File]::ReadAllLines($envFile)
        $found = $false
        $next = foreach ($line in $lines) {
            if ($line -match ('^\s*' + [regex]::Escape($Variable) + '\s*=')) { $found = $true; "$Variable=$secret" } else { $line }
        }
        if (-not $found) { $next += "$Variable=$secret" }
        & git -C $repoRoot check-ignore --quiet -- $envFile
        if ($LASTEXITCODE -ne 0) { throw 'Secret destination is not ignored by Git' }
        [IO.File]::WriteAllLines($envFile, $next, (New-Object Text.UTF8Encoding($false)))
        Write-Output '{"local_environment_updated":true,"secret_disclosed":false}'
        exit 0
    }
    if ($Environment -ne 'qa') { throw 'Production application requires a separately approved procedure' }
    if (-not $Service) { throw 'Service is required' }
    if ($Service -eq 'web' -and $Variable -ne 'SUPABASE_SERVICE_ROLE_KEY') { throw 'Variable is not authorized for web' }
    $serviceId = if ($Service -eq 'api') { '15c25be0-4ecd-49c8-87c1-da675c2b9d01' } else { '125116d7-0720-412d-9180-2205169c628f' }
    $railway = (Get-Command railway.exe -ErrorAction Stop).Source
    $start = New-Object Diagnostics.ProcessStartInfo
    $start.FileName = $railway
    $start.Arguments = "variable set $Variable --stdin --project 33726923-021d-47a7-a263-b8b287f164f1 --environment 97b0366d-a965-4356-88fd-f66dc45e83b9 --service $serviceId"
    if ($SkipDeploys) { $start.Arguments += ' --skip-deploys' }
    $start.UseShellExecute = $false
    $start.CreateNoWindow = $true
    $start.RedirectStandardInput = $true
    $start.RedirectStandardOutput = $true
    $start.RedirectStandardError = $true
    $process = [Diagnostics.Process]::Start($start)
    $process.StandardInput.Write($secret)
    $process.StandardInput.Close()
    # Suppress CLI output, including error text: some CLI versions echo values.
    $stdout = $process.StandardOutput.ReadToEndAsync()
    $stderr = $process.StandardError.ReadToEndAsync()
    if (-not $process.WaitForExit(120000)) { $process.Kill(); throw 'Railway operation timed out; inspect remote state' }
    $null = $stdout.Result
    $null = $stderr.Result
    if ($process.ExitCode -ne 0) { throw 'Railway operation failed' }
    Write-Output '{"railway_updated":true,"secret_disclosed":false,"verification_required":true}'
} catch {
    Write-Error 'Recovery operation failed. No secret or provider error was logged.'
    exit 1
} finally {
    $secret = $null
}
